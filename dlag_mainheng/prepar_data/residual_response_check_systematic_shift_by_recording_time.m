function tags = get_all_run_tags_local(model_data_allruns)
tags = cell(numel(model_data_allruns), 1);
for i = 1:numel(model_data_allruns)
    if ~isstruct(model_data_allruns{i}) || ...
            ~isfield(model_data_allruns{i}, 'stim_tag')
        error('model_data_allruns{%d} is missing stim_tag.', i);
    end
    tags{i} = model_data_allruns{i}.stim_tag;
end
end

function values = normalize_text_list_local(values, variable_name, allow_empty)
if nargin < 3
    allow_empty = false;
end

if isempty(values)
    if allow_empty
        values = {};
        return;
    end
    error('%s must not be empty.', variable_name);
end

if ischar(values)
    values = {values};
elseif isstring(values)
    values = cellstr(values(:));
elseif iscell(values)
    values = values(:);
else
    error('%s must contain text values.', variable_name);
end

out = cell(1, numel(values));
for i = 1:numel(values)
    value = values{i};
    if isstring(value) && isscalar(value)
        value = char(value);
    end
    if ~ischar(value) || isempty(strtrim(value))
        error('%s{%d} must be one nonempty text value.', variable_name, i);
    end
    out{i} = strtrim(value);
end
values = out;
end

function [groupd, field_name] = get_groupd_for_field_local(run_entry, data_field)
specific_field = sprintf('%s_groupd', data_field);
if isfield(run_entry, specific_field)
    groupd = run_entry.(specific_field);
    field_name = specific_field;
elseif isfield(run_entry, 'groupd')
    groupd = run_entry.groupd;
    field_name = 'groupd';
else
    error('Neither %s nor groupd exists in the selected run.', specific_field);
end

groupd = double(groupd(:)');
if isempty(groupd) || any(~isfinite(groupd)) || ...
        any(groupd < 0) || any(groupd ~= round(groupd))
    error('%s must contain finite nonnegative integer group sizes.', field_name);
end
end

function [trial_ids, condition_index, response_by_unit, n_time_bins] = ...
        build_trial_response_matrix_local(run_entry, data_field, reduction)

trial_data = run_entry.(data_field);
if ~isstruct(trial_data) || isempty(trial_data) || ...
        ~isfield(trial_data, 'trialId') || ...
        ~isfield(trial_data, 'T') || ...
        ~isfield(trial_data, 'y')
    error('%s must be a nonempty trial struct array with trialId, T, and y.', ...
        data_field);
end

n_trials = numel(trial_data);
unsorted_trial_ids = zeros(1, n_trials);
for i = 1:n_trials
    unsorted_trial_ids(i) = trial_data(i).trialId;
end

if any(~isfinite(unsorted_trial_ids)) || ...
        any(unsorted_trial_ids < 1) || ...
        any(unsorted_trial_ids ~= round(unsorted_trial_ids))
    error('%s contains invalid trialId values.', data_field);
end
if numel(unique(unsorted_trial_ids)) ~= n_trials
    error('%s contains duplicate trialId values.', data_field);
end

[trial_ids, sort_order] = sort(unsorted_trial_ids, 'ascend');
trial_data = trial_data(sort_order);

first_y = trial_data(1).y;
if ~isnumeric(first_y) || ndims(first_y) > 2 || isempty(first_y)
    error('%s trial 1 contains an invalid y matrix.', data_field);
end

n_units = size(first_y, 1);
n_time_bins = size(first_y, 2);
response_by_unit = nan(n_units, n_trials);

for i = 1:n_trials
    y = trial_data(i).y;
    if ~isnumeric(y) || ~isequal(size(y), [n_units, n_time_bins])
        error(['%s has inconsistent y size at trialId %d. Expected ', ...
            '%d x %d.'], data_field, trial_data(i).trialId, ...
            n_units, n_time_bins);
    end
    if ~isscalar(trial_data(i).T) || trial_data(i).T ~= n_time_bins
        error('%s has inconsistent T at trialId %d.', ...
            data_field, trial_data(i).trialId);
    end
    if any(~isfinite(y(:)))
        error(['Nonfinite residual values were found in %s at trialId %d. ', ...
            'Use a model-data NaN strategy that provides finite values.'], ...
            data_field, trial_data(i).trialId);
    end

    switch reduction
        case 'sum'
            response_by_unit(:, i) = sum(y, 2);
        case 'mean'
            response_by_unit(:, i) = mean(y, 2);
        otherwise
            error('Unknown time-bin reduction: %s', reduction);
    end
end

full_condition_index = run_entry.condition_index_per_trial_full(:)';
if any(trial_ids > numel(full_condition_index))
    error(['At least one retained trialId exceeds the length of ', ...
        'condition_index_per_trial_full.']);
end
condition_index = full_condition_index(trial_ids);
end

function ranges = make_group_row_ranges_local(groupd)
ranges = cell(1, numel(groupd));
row_start = 1;
for g = 1:numel(groupd)
    row_end = row_start + groupd(g) - 1;
    if groupd(g) == 0
        ranges{g} = zeros(1, 0);
    else
        ranges{g} = row_start:row_end;
    end
    row_start = row_end + 1;
end
end

function labels = build_condition_labels_local(run_entry, n_conditions)
if isfield(run_entry, 'condition_fields')
    condition_fields = normalize_text_list_local( ...
        run_entry.condition_fields, 'condition_fields', true);
else
    condition_fields = {};
end

labels = cell(1, n_conditions);
for c = 1:n_conditions
    parts = cell(1, 0);
    for k = 1:numel(condition_fields)
        f = condition_fields{k};
        if isfield(run_entry.conditions_full(c), f)
            parts{end + 1} = sprintf('%s=%s', f, ...
                value_to_text_local(run_entry.conditions_full(c).(f))); %#ok<AGROW>
        end
    end

    if isempty(parts)
        labels{c} = sprintf('Condition %d', c);
    else
        labels{c} = sprintf('C%d: %s', c, strjoin(parts, ', '));
    end
end
end

function text_value = value_to_text_local(value)
if isnumeric(value)
    if isempty(value)
        text_value = '[]';
    elseif isscalar(value)
        text_value = sprintf('%.6g', value);
    else
        text_value = mat2str(value);
    end
elseif islogical(value)
        text_value = mat2str(value);
elseif ischar(value)
    text_value = value;
elseif isstring(value)
    text_value = strjoin(cellstr(value(:)), '|');
elseif iscategorical(value)
    text_value = strjoin(cellstr(string(value(:))), '|');
elseif iscell(value)
    pieces = cell(size(value));
    for i = 1:numel(value)
        pieces{i} = value_to_text_local(value{i});
    end
    text_value = strjoin(pieces(:)', '|');
else
    try
        text_value = char(string(value));
    catch
        text_value = class(value);
    end
end
end

function labels = build_unit_labels_local( ...
        run_entry, data_field, selected_rows, group_names, groupd, ranges)

labels = cell(1, numel(selected_rows));

if isfield(run_entry, 'group_probe')
    group_probe = double(run_entry.group_probe(:)');
    if numel(group_probe) ~= numel(groupd)
        error('group_probe and groupd must contain the same number of groups.');
    end
else
    group_probe = nan(size(groupd));
end

for i = 1:numel(selected_rows)
    model_row = selected_rows(i);
    group_index = find(cellfun(@(x) any(x == model_row), ranges), 1);
    if isempty(group_index)
        error('Could not map model row %d to one group.', model_row);
    end

    area_name = group_names{group_index};
    within_group_index = model_row - ranges{group_index}(1) + 1;
    probe_index = group_probe(group_index);
    found_unit_id = false;
    unit_id = NaN;

    if isfinite(probe_index)
        preceding_same_probe = find( ...
            group_probe(1:group_index-1) == probe_index);
        probe_local_offset = sum(groupd(preceding_same_probe));
        probe_local_index = probe_local_offset + within_group_index;

        field_specific_ids = sprintf('%s_probe%d_usedunit_ids', ...
            data_field, probe_index);
        common_ids = sprintf('probe%d_usedunit_ids', probe_index);

        if isfield(run_entry, field_specific_ids)
            ids = run_entry.(field_specific_ids);
        elseif isfield(run_entry, common_ids)
            ids = run_entry.(common_ids);
        else
            ids = [];
        end

        ids = ids(:);
        if probe_local_index >= 1 && probe_local_index <= numel(ids)
            unit_id = ids(probe_local_index);
            found_unit_id = isnumeric(unit_id) && isscalar(unit_id) && ...
                isfinite(unit_id);
        end
    end

    if found_unit_id
        labels{i} = sprintf('%s | prb%d unit %.0f', ...
            area_name, probe_index, unit_id);
    elseif isfinite(probe_index)
        labels{i} = sprintf('%s | prb%d model row %d', ...
            area_name, probe_index, model_row);
    else
        labels{i} = sprintf('%s | model row %d', area_name, model_row);
    end
end
end

function lim = padded_limits_including_zero_local(values)
values = values(isfinite(values));
if isempty(values)
    lim = [-1 1];
    return;
end

lo = min([values(:); 0]);
hi = max([values(:); 0]);

if hi == lo
    pad = max(1, abs(hi) * 0.1);
else
    pad = 0.08 * (hi - lo);
end
lim = [lo - pad, hi + pad];
end

function x_limits = padded_trial_limits_local(trial_ids)
lo = min(trial_ids);
hi = max(trial_ids);
if hi == lo
    x_limits = [lo - 0.5, hi + 0.5];
else
    pad = max(0.5, 0.01 * (hi - lo));
    x_limits = [lo - pad, hi + pad];
end
end

function hfig = plot_condition_grid_local( ...
        trial_ids, condition_index, response_by_unit, selected_rows, ...
        unit_labels, row_ylimits, condition_labels, condition_colors, ...
        area_name, stim_tag, reduction, figure_visibility, ...
        line_width, marker_size, zero_line_color, ...
        axis_font_size, title_font_size, ...
        width_per_condition, height_per_unit)

n_rows = numel(selected_rows);
n_conditions = numel(condition_labels);
x_limits = padded_trial_limits_local(trial_ids);

figure_width = max(1400, width_per_condition * n_conditions);
figure_height = max(900, height_per_unit * n_rows);

hfig = figure('Color', 'w', ...
    'Visible', figure_visibility, ...
    'Name', sprintf('%s residual shift: condition grid', area_name), ...
    'Position', [40 40 figure_width figure_height]);

tl = tiledlayout(n_rows, n_conditions, ...
    'TileSpacing', 'compact', 'Padding', 'compact');

for r = 1:n_rows
    model_row = selected_rows(r);
    for c = 1:n_conditions
        ax = nexttile(tl);
        take = (condition_index == c);

        hold(ax, 'on');
        if any(take)
            plot(ax, trial_ids(take), response_by_unit(model_row, take), ...
                '-o', ...
                'Color', condition_colors(c, :), ...
                'MarkerFaceColor', condition_colors(c, :), ...
                'MarkerEdgeColor', condition_colors(c, :), ...
                'LineWidth', line_width, ...
                'MarkerSize', marker_size);
        else
            text(ax, mean(x_limits), mean(row_ylimits(r, :)), ...
                'No trials', 'HorizontalAlignment', 'center', ...
                'Color', [0.5 0.5 0.5]);
        end

        yline(ax, 0, '--', 'Color', zero_line_color, 'LineWidth', 0.7);
        xlim(ax, x_limits);
        ylim(ax, row_ylimits(r, :));
        grid(ax, 'on');
        box(ax, 'on');
        ax.FontSize = axis_font_size;

        if r == 1
            title(ax, condition_labels{c}, ...
                'Interpreter', 'none', 'FontSize', title_font_size);
        end
        if c == 1
            ylabel(ax, sprintf('%s\nResponse', unit_labels{r}), ...
                'Interpreter', 'none');
        else
            ax.YTickLabel = [];
        end
        if r == n_rows
            xlabel(ax, 'Global trial ID');
        else
            ax.XTickLabel = [];
        end
    end
end

sgtitle(tl, sprintf(['%s | %s | residual response by recording time | ', ...
    'conditions separated | time-bin %s'], ...
    area_name, stim_tag, reduction), 'Interpreter', 'none');
end

function hfig = plot_conditions_together_local( ...
        trial_ids, condition_index, response_by_unit, selected_rows, ...
        unit_labels, row_ylimits, condition_labels, condition_colors, ...
        area_name, stim_tag, reduction, figure_visibility, ...
        line_width, marker_size, zero_line_color, ...
        axis_font_size, figure_width, height_per_unit)

n_rows = numel(selected_rows);
n_conditions = numel(condition_labels);
x_limits = padded_trial_limits_local(trial_ids);
figure_height = max(900, height_per_unit * n_rows);

hfig = figure('Color', 'w', ...
    'Visible', figure_visibility, ...
    'Name', sprintf('%s residual shift: conditions together', area_name), ...
    'Position', [60 40 figure_width figure_height]);

tl = tiledlayout(n_rows, 1, ...
    'TileSpacing', 'compact', 'Padding', 'compact');

legend_handles = gobjects(1, n_conditions);
first_axis = [];

for r = 1:n_rows
    model_row = selected_rows(r);
    ax = nexttile(tl);
    if r == 1
        first_axis = ax;
    end
    hold(ax, 'on');

    for c = 1:n_conditions
        take = (condition_index == c);
        if ~any(take)
            continue;
        end

        h = plot(ax, trial_ids(take), response_by_unit(model_row, take), ...
            '-o', ...
            'Color', condition_colors(c, :), ...
            'MarkerFaceColor', condition_colors(c, :), ...
            'MarkerEdgeColor', condition_colors(c, :), ...
            'LineWidth', line_width, ...
            'MarkerSize', marker_size);

        if r == 1
            legend_handles(c) = h;
        end
    end

    yline(ax, 0, '--', 'Color', zero_line_color, 'LineWidth', 0.7);
    xlim(ax, x_limits);
    ylim(ax, row_ylimits(r, :));
    grid(ax, 'on');
    box(ax, 'on');
    ax.FontSize = axis_font_size;
    ylabel(ax, sprintf('%s\nResponse', unit_labels{r}), ...
        'Interpreter', 'none');

    if r == n_rows
        xlabel(ax, 'Global trial ID');
    else
        ax.XTickLabel = [];
    end
end

valid_legend = isgraphics(legend_handles);
if any(valid_legend)
    lgd = legend(first_axis, legend_handles(valid_legend), ...
        condition_labels(valid_legend), ...
        'Interpreter', 'none', 'Location', 'eastoutside');
    try
        lgd.Layout.Tile = 'east';
    catch
        % Older MATLAB versions keep the legend beside the first axes.
    end
end

sgtitle(tl, sprintf(['%s | %s | residual response by recording time | ', ...
    'conditions together, connected separately | time-bin %s'], ...
    area_name, stim_tag, reduction), 'Interpreter', 'none');
end

function save_figure_local(hfig, output_dir, base_name, ...
        save_png, save_matlab_fig, png_dpi)

if save_png
    png_file = fullfile(output_dir, [base_name '.png']);
    try
        exportgraphics(hfig, png_file, 'Resolution', png_dpi);
    catch
        print(hfig, png_file, '-dpng', sprintf('-r%d', round(png_dpi)));
    end
    fprintf('Saved PNG: %s\n', png_file);
end

if save_matlab_fig
    fig_file = fullfile(output_dir, [base_name '.fig']);
    savefig(hfig, fig_file);
    fprintf('Saved FIG: %s\n', fig_file);
end
end

function safe_tag = make_safe_file_tag_local(text_value, max_length)
if isstring(text_value) && isscalar(text_value)
    text_value = char(text_value);
end
if ~ischar(text_value)
    text_value = char(string(text_value));
end

safe_tag = regexprep(text_value, '[^A-Za-z0-9_-]+', '_');
safe_tag = regexprep(safe_tag, '_+', '_');
safe_tag = regexprep(safe_tag, '^_+|_+$', '');

if isempty(safe_tag)
    safe_tag = 'unnamed';
end
if numel(safe_tag) > max_length
    safe_tag = safe_tag(1:max_length);
end
end
